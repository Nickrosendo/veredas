#!/usr/bin/env python3
"""
Turns the 16 x 16 icon pictures in tools/art/icons/ into src/gfx/icons_data.c:
one shared table of colours, and per icon 256 small numbers, row after row,
each an index into that table (0: nothing drawn there).

The icons are read in the order of src/gfx/icons.h's enum, read from the
header itself, so a picture can't land on the wrong icon: ICON_ZOOM_OUT is
zoom_out.png. A missing picture, a wrong size, a half-transparent pixel or
more than 255 colours stops the conversion with a message.

Run:  python3 tools/art/icons_to_c.py tools/art/icons > src/gfx/icons_data.c
      (needs Pillow)
"""
import os
import re
import sys

from PIL import Image

SIZE = 16
HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = os.path.join(HERE, "..", "..", "src", "gfx", "icons.h")


def icon_names():
    """ICON_ names from the header's enum, in order, without ICON_SIZE and
    ICON_COUNT."""
    text = open(HEADER).read()
    body = re.search(r"enum\s*{([^}]*)}", text).group(1)
    names = re.findall(r"\b(ICON_[A-Z_]+)\b", body)
    return [n for n in names if n != "ICON_COUNT"]


def fail(message):
    sys.stderr.write("icons_to_c: " + message + "\n")
    sys.exit(1)


def main():
    if len(sys.argv) != 2:
        fail("usage: icons_to_c.py ICON_DIR > src/gfx/icons_data.c")
    folder = sys.argv[1]
    colours = []  # (r, g, b); index i + 1 in the C table
    inks = []
    for name in icon_names():
        path = os.path.join(folder, name[len("ICON_"):].lower() + ".png")
        if not os.path.exists(path):
            fail("no picture for %s: %s" % (name, path))
        im = Image.open(path).convert("RGBA")
        if im.size != (SIZE, SIZE):
            fail("%s is %dx%d, not %dx%d" % (path, im.size[0], im.size[1],
                                             SIZE, SIZE))
        ink = []
        for y in range(SIZE):
            for x in range(SIZE):
                r, g, b, a = im.getpixel((x, y))
                if a == 0:
                    ink.append(0)
                    continue
                if a != 255:
                    fail("%s: pixel %d,%d is half transparent" % (path, x, y))
                if (r, g, b) not in colours:
                    colours.append((r, g, b))
                ink.append(colours.index((r, g, b)) + 1)
        inks.append((name, ink))
    if len(colours) > 255:
        fail("%d colours: an index is one byte, 255 at most" % len(colours))

    out = sys.stdout
    out.write("/* Generated by tools/art/icons_to_c.py from tools/art/icons/: "
              "do not edit.\n"
              " * ICON_INK[icon] holds 16 rows of 16 indexes into ICON_COLOURS;"
              " 0 is not drawn. */\n")
    out.write('#include "icons.h"\n\n')
    out.write("const uint32_t ICON_COLOURS[ICON_COLOUR_COUNT] = {\n")
    out.write("    0x00000000u, /* 0: nothing */\n")
    for r, g, b in colours:
        out.write("    0xFF%02X%02X%02Xu,\n" % (r, g, b))
    out.write("};\n\n")
    out.write("const uint8_t ICON_INK[ICON_COUNT][ICON_SIZE * ICON_SIZE] = {\n")
    for name, ink in inks:
        out.write("    [%s] = {\n" % name)
        for y in range(SIZE):
            row = ink[y * SIZE:(y + 1) * SIZE]
            out.write("        " + ",".join("%d" % v for v in row) + ",\n")
        out.write("    },\n")
    out.write("};\n")
    sys.stderr.write("icons_to_c: %d icons, %d colours\n"
                     % (len(inks), len(colours)))
    # The header's ICON_COLOUR_COUNT must be the table's length: say it.
    sys.stderr.write("icons_to_c: ICON_COLOUR_COUNT must be %d\n"
                     % (len(colours) + 1))


if __name__ == "__main__":
    main()
