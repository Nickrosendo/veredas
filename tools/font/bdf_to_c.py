#!/usr/bin/env python3
"""Turns Spleen 8x16 into src/gfx/text_data.c, the window's two fonts.

Source: Spleen 2.2.0 by Frederic Cambus, BSD 2-clause licence
(licenses/BSD-Spleen.txt), from
https://github.com/fcambus/spleen/releases/download/2.2.0/spleen-2.2.0.tar.gz
(the file spleen-8x16.bdf in it, copied beside this script).

Both fonts come from the same glyphs:
- fixed: each glyph as it is, 8 wide, for columns lined up by spaces;
- proportional: each glyph cut to its inked columns, so an 'i' is narrow and
  a 'W' wide; text.c puts one empty column between letters.

Run from the repository's root:  python3 tools/font/bdf_to_c.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BDF = os.path.join(HERE, "spleen-8x16.bdf")
OUT = os.path.join(HERE, "..", "..", "src", "gfx", "text_data.c")

FIRST, LAST = 32, 126
SPACE_W = 4  # the space has no ink; this is its width in the proportional font


def read_bdf(path):
    """Returns {code: [16 row bytes]}, the leftmost pixel in the top bit."""
    glyphs, code, rows = {}, None, None
    with open(path) as f:
        for line in f:
            t = line.split()
            if not t:
                continue
            if t[0] == "ENCODING":
                code = int(t[1])
            elif t[0] == "BBX":
                # every glyph in Spleen 8x16 fills the whole cell
                assert t[1:] == ["8", "16", "0", "-4"], (code, t)
            elif t[0] == "BITMAP":
                rows = []
            elif t[0] == "ENDCHAR":
                glyphs[code] = rows
                rows = None
            elif rows is not None:
                rows.append(int(t[0], 16))
    return glyphs


def inked_columns(rows):
    """(first, width) of the inked columns, column 0 the leftmost."""
    cols = [c for c in range(8) if any((r >> (7 - c)) & 1 for r in rows)]
    if not cols:
        return 0, 0
    return min(cols), max(cols) - min(cols) + 1


def main():
    glyphs = read_bdf(BDF)
    lines = [
        "/* Generated by tools/font/bdf_to_c.py from Spleen 8x16 (BSD 2-clause,",
        " * licenses/BSD-Spleen.txt): do not edit.",
        " * TEXT_ROWS[i] is the glyph of ASCII 32 + i, 16 rows, the leftmost pixel",
        " * in the top bit. TEXT_LEFT and TEXT_WIDTH cut it to its inked columns for",
        " * the proportional font. */",
        '#include "text.h"',
        "",
        "const uint8_t TEXT_ROWS[TEXT_GLYPHS][TEXT_H] = {",
    ]
    left, width = [], []
    for code in range(FIRST, LAST + 1):
        rows = glyphs[code]
        assert len(rows) == 16, code
        first, w = inked_columns(rows)
        if code == 32:
            first, w = 0, SPACE_W
        left.append(first)
        width.append(w)
        shown = chr(code) if chr(code) not in "\\*/" else "code %d" % code
        lines.append("    {" + ", ".join("0x%02X" % r for r in rows) + "}, /* " + shown + " */")
    lines.append("};")
    lines.append("")
    lines.append("const uint8_t TEXT_LEFT[TEXT_GLYPHS] = {")
    for i in range(0, len(left), 16):
        lines.append("    " + ", ".join(str(v) for v in left[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("const uint8_t TEXT_WIDTH[TEXT_GLYPHS] = {")
    for i in range(0, len(width), 16):
        lines.append("    " + ", ".join(str(v) for v in width[i:i + 16]) + ",")
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
